// Regenerates src/domain/data/players.ts from ESPN's public NBA roster API.
// Run: npm run sync:players
import { writeFileSync } from 'node:fs'

const API = 'https://site.api.espn.com/apis/site/v2/sports/basketball/nba'

async function getJson(url) {
  const res = await fetch(url)
  if (!res.ok) throw new Error(`${res.status} ${url}`)
  return res.json()
}

// Accents stripped so names match the ASCII style StatMuse questions use.
const ascii = (s) => s.normalize('NFD').replace(/[̀-ͯ]/g, '').trim()

const teams = (await getJson(`${API}/teams`)).sports[0].leagues[0].teams.map((t) => t.team)
if (teams.length !== 30) throw new Error(`expected 30 teams, got ${teams.length}`)

const names = new Set()
let season = ''
for (const team of teams) {
  const roster = await getJson(`${API}/teams/${team.id}/roster`)
  season ||= roster.season.displayName
  for (const a of roster.athletes) names.add(ascii(a.fullName))
}

const sorted = [...names].sort((a, b) => {
  const last = (n) => n.split(' ').slice(1).join(' ')
  return last(a).localeCompare(last(b)) || a.localeCompare(b)
})
const today = new Date().toISOString().slice(0, 10)

writeFileSync(
  new URL('../src/domain/data/players.ts', import.meta.url),
  `/**
 * Autocomplete suggestions for the player box.
 *
 * Source: ESPN's public NBA roster API, all 30 teams' ${season} rosters
 * (${sorted.length} names), synced ${today}. Generated by
 * scripts/sync-players.mjs (\`npm run sync:players\`); don't edit by hand.
 * The box accepts any typed name; this list only powers suggestions.
 */
export const PLAYERS_SEASON = '${season}'

export const PLAYERS: readonly string[] = [
${sorted.map((n) => `  ${JSON.stringify(n)},`).join('\n')}
]
`,
)
console.log(`${season}: ${sorted.length} players from ${teams.length} teams`)
